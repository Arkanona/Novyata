import { expect, test } from '@playwright/test'
import { authenticatedPage, mockApi } from './fixtures.js'

test('authentification : inscription, dashboard, déconnexion et route privée', async ({ page }) => {
  await mockApi(page)
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/connexion$/)
  await page.goto('/inscription')
  await page.getByLabel('Prénom').fill('Élise')
  await page.getByLabel('Nom', { exact: true }).fill('Durand')
  await page.getByLabel('Adresse e-mail').fill('elise.e2e@example.test')
  await page.locator('input[name="password"]').fill('password-e2e')
  await page.getByLabel('Confirmer le mot de passe').fill('password-e2e')
  await page.getByRole('button', { name: 'Créer mon compte' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await expect(page.getByRole('heading', { name: "Vue d'ensemble" })).toBeVisible()
  await page.getByRole('button', { name: 'Déconnexion' }).click()
  await expect(page).toHaveURL(/\/connexion$/)
})

