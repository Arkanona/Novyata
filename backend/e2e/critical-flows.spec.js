test('dépassement A4 : sauvegarde et export sont bloqués', async ({ page }) => {
  const state = await authenticatedPage(page)
  state.resume.summary = 'Contenu de test très long. '.repeat(800)
  await page.goto('/cv/f8c5d2f2-6ff2-43d2-9e4f-5443200f6d4b')
  await expect(page.getByRole('alert')).toContainText('dépasse une page A4')
  await expect(page.getByRole('button', { name: 'Télécharger en PDF' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true }).first()).toBeDisabled()
})

test('lettres et candidatures : liaison, sauvegarde, statut et filtre', async ({ page }) => {
  await authenticatedPage(page)
  await page.goto('/lettres/nouvelle')
  await page.getByLabel('Titre interne').fill('Lettre Novyata')
  await page.getByLabel('CV associé').selectOption({ index: 1 })
  await page.getByLabel('Contenu').fill('Madame, Monsieur, je souhaite vous proposer ma candidature pour ce poste de Product Designer.')
  await page.getByRole('button', { name: 'Créer la lettre' }).click()
  await expect(page).toHaveURL(/\/lettres\//)
  await page.getByLabel('Objet').fill('Candidature Product Designer')
  await page.getByRole('button', { name: 'Enregistrer les modifications' }).click()
  await expect(page.getByText('Modifications enregistrées.')).toBeVisible()
  await page.goto('/candidatures/nouvelle')
  await page.getByLabel('Entreprise').fill('Novyata')
  await page.getByLabel('Poste').fill('Product Designer')
  await page.getByLabel('CV associé').selectOption({ index: 1 })
  await page.getByLabel('Lettre associée').selectOption({ index: 1 })
  await page.getByLabel('Statut').selectOption('Entretien')
  await page.getByRole('button', { name: 'Ajouter la candidature' }).click()
  await expect(page).toHaveURL(/\/candidatures\//)
  await page.goto('/candidatures')
  await expect(page.getByText('Novyata')).toBeVisible()
  await page.getByRole('combobox').nth(0).selectOption('Entretien')
  await expect(page.getByText('Product Designer')).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Supprimer Novyata' }).click()
  await expect(page.getByText('Vous n’avez encore aucune candidature.')).toBeVisible()
})

